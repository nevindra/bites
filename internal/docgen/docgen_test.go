package docgen_test

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/nevindra/bites/internal/docgen"
)

func pkg(t *testing.T, files map[string]string) string {
	t.Helper()
	dir := t.TempDir()
	for n, s := range files {
		if err := os.WriteFile(filepath.Join(dir, n), []byte(s), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return dir
}

func TestTheCommittedExampleIsWhatTheGeneratorWritesNow(t *testing.T) {
	dir := filepath.Join("..", "..", "examples", "described")
	res, err := docgen.Generate(dir, docgen.Options{})
	if err != nil {
		t.Fatal(err)
	}
	have, err := os.ReadFile(filepath.Join(dir, docgen.FileName))
	if err != nil {
		t.Fatal(err)
	}
	if string(have) != string(res.Source) {
		t.Fatalf("%s is out of date: run go generate in examples/described", docgen.FileName)
	}
}

func TestACommentAboveAFieldOrAfterItBecomesItsDescriptionWithParagraphsKept(t *testing.T) {
	dir := pkg(t, map[string]string{"a.go": `package a

type T struct {
	// First line
	// second line.
	//
	// Next paragraph.
	A int
	B int // trailing
	C int
	d int // unexported
}
`})
	res, err := docgen.Generate(dir, docgen.Options{})
	if err != nil {
		t.Fatal(err)
	}
	src := string(res.Source)
	for _, want := range []string{`"A": "First line second line.\n\nNext paragraph."`, `"B": "trailing"`} {
		if !strings.Contains(src, want) {
			t.Errorf("missing %s in\n%s", want, src)
		}
	}
	if strings.Contains(src, `"C"`) || strings.Contains(src, `"d"`) {
		t.Errorf("an undocumented or unexported field is described:\n%s", src)
	}
	if !strings.HasPrefix(src, "// Code generated by bites-doc; DO NOT EDIT.") {
		t.Errorf("no generated header:\n%s", src)
	}
}

func TestATypeWithAHandWrittenDescriptionsMethodIsLeftAloneAndSaid(t *testing.T) {
	dir := pkg(t, map[string]string{
		"a.go": `package a

type T struct {
	// A is a.
	A int
}

type U struct {
	// B is b.
	B int
}

func (T) Descriptions() map[string]string { return map[string]string{"A": "by hand"} }
`})
	res, err := docgen.Generate(dir, docgen.Options{})
	if err != nil {
		t.Fatal(err)
	}
	if len(res.Types) != 1 || res.Types[0] != "U" {
		t.Fatalf("types %v", res.Types)
	}
	if len(res.Notes) != 1 || !strings.Contains(res.Notes[0], "T: has a Descriptions method written by hand") {
		t.Fatalf("notes %v", res.Notes)
	}
}

func TestAnAnonymousSectionAGenericTypeAndAFieldOffTheWireAreSaidAndNotWritten(t *testing.T) {
	dir := pkg(t, map[string]string{"a.go": `package a

type In struct {
	Path struct {
		// ID is the id.
		ID int
	}
}

type G[T any] struct {
	// V is a value.
	V T
}

type W struct {
	// Hidden is not sent.
	Hidden string ` + "`json:\"-\"`" + `
}
`})
	res, err := docgen.Generate(dir, docgen.Options{})
	if err != nil {
		t.Fatal(err)
	}
	if res.Source != nil {
		t.Fatalf("something was written:\n%s", res.Source)
	}
	joined := strings.Join(res.Notes, "\n")
	for _, want := range []string{"In.Path: is an anonymous struct", "G: a generic type", "W.Hidden: has a comment but is not on the wire"} {
		if !strings.Contains(joined, want) {
			t.Errorf("no note %q in\n%s", want, joined)
		}
	}
}

func TestTypesLimitsTheOutputAndAStaleFileIsRemovedWhenNothingIsLeft(t *testing.T) {
	dir := pkg(t, map[string]string{"a.go": `package a

type T struct {
	// A is a.
	A int
}

type U struct {
	// B is b.
	B int
}
`})
	res, changed, err := docgen.Write(dir, docgen.Options{Types: []string{"U"}})
	if err != nil || !changed || len(res.Types) != 1 || res.Types[0] != "U" {
		t.Fatalf("%v %v %v", res, changed, err)
	}
	if _, changed, _ := docgen.Write(dir, docgen.Options{Types: []string{"U"}}); changed {
		t.Fatal("a second run changed the file")
	}
	os.WriteFile(filepath.Join(dir, "a.go"), []byte("package a\n\ntype T struct{ A int }\n"), 0o644)
	if _, changed, _ := docgen.Write(dir, docgen.Options{}); !changed {
		t.Fatal("the stale file stayed")
	}
	if _, err := os.Stat(filepath.Join(dir, docgen.FileName)); !os.IsNotExist(err) {
		t.Fatalf("the stale file is still there: %v", err)
	}
}

func TestTheOutputOfTwoRunsIsIdentical(t *testing.T) {
	dir := filepath.Join("..", "..", "examples", "described")
	a, _ := docgen.Generate(dir, docgen.Options{})
	for range 5 {
		b, _ := docgen.Generate(dir, docgen.Options{})
		if string(a.Source) != string(b.Source) {
			t.Fatal("the output depends on map order")
		}
	}
}

func TestAnUnexportedStructTypeWithADocumentedFieldGetsAMethodLikeAnExportedOne(t *testing.T) {
	dir := pkg(t, map[string]string{"a.go": `package a

type customerIDPath struct {
	// ID is the customer id.
	ID string
}

type listQuery struct {
	customerIDPath
	// Page counts from 1.
	Page int
}
`})
	res, err := docgen.Generate(dir, docgen.Options{})
	if err != nil {
		t.Fatal(err)
	}
	src := string(res.Source)
	for _, want := range []string{"func (customerIDPath) Descriptions()", "func (listQuery) Descriptions()", `"Page": "Page counts from 1."`, `"ID": "ID is the customer id."`} {
		if !strings.Contains(src, want) {
			t.Errorf("missing %q in\n%s", want, src)
		}
	}
	if len(res.Types) != 2 {
		t.Errorf("types %v", res.Types)
	}
}
