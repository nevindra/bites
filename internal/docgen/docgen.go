// Package docgen reads the Go doc comments of the struct types of one package and writes the
// Descriptions methods that bites reads (ADR 0020, ADR 0072). A comment above a field, or after
// it on the same line, becomes that field's description in the API document, so a project writes
// its prose once, where Go programmers already write it. The package uses the standard library
// only and is driven by cmd/bites-doc.
package docgen

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"reflect"
	"slices"
	"sort"
	"strconv"
	"strings"
)

// FileName is the generated file, in the package it describes.
const FileName = "bites_descriptions_gen.go"

const header = "// Code generated by bites-doc; DO NOT EDIT.\n"

// Options narrows what is generated.
type Options struct {
	// Types limits generation to these type names; every named struct type with a documented field
	// when empty.
	Types []string
}

// Result is a generated file and what the generator left out.
type Result struct {
	// Source is the formatted Go file, nil when no type has a description to write.
	Source []byte
	// Types are the names that got a method, sorted.
	Types []string
	// Notes say, one a line, what was skipped and why: a documented field the generator could not
	// attach, or a type that already has a hand-written method.
	Notes []string
}

// Generate parses the package in dir (test files and the generated file itself excluded) and
// returns the Descriptions methods for its documented struct types.
func Generate(dir string, opt Options) (*Result, error) {
	fset := token.NewFileSet()
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	var files []*ast.File
	for _, e := range entries {
		n := e.Name()
		if e.IsDir() || !strings.HasSuffix(n, ".go") || strings.HasSuffix(n, "_test.go") || n == FileName {
			continue
		}
		f, err := parser.ParseFile(fset, filepath.Join(dir, n), nil, parser.ParseComments)
		if err != nil {
			return nil, err
		}
		files = append(files, f)
	}
	if len(files) == 0 {
		return nil, fmt.Errorf("docgen: no Go files in %s", dir)
	}
	pkg := files[0].Name.Name
	structs := map[string]*ast.StructType{}
	generic := map[string]bool{}
	hand := map[string]bool{} // types with a Descriptions method written by hand
	for _, f := range files {
		if f.Name.Name != pkg {
			return nil, fmt.Errorf("docgen: %s holds packages %s and %s", dir, pkg, f.Name.Name)
		}
		for _, d := range f.Decls {
			switch d := d.(type) {
			case *ast.GenDecl:
				for _, s := range d.Specs {
					if ts, ok := s.(*ast.TypeSpec); ok {
						if st, ok := ts.Type.(*ast.StructType); ok {
							structs[ts.Name.Name] = st
							generic[ts.Name.Name] = ts.TypeParams != nil
						}
					}
				}
			case *ast.FuncDecl:
				if d.Name.Name == "Descriptions" && d.Recv != nil && len(d.Recv.List) == 1 {
					hand[recvName(d.Recv.List[0].Type)] = true
				}
			}
		}
	}
	res := &Result{}
	want := func(name string) bool { return len(opt.Types) == 0 || slices.Contains(opt.Types, name) }
	names := make([]string, 0, len(structs))
	for n := range structs {
		names = append(names, n)
	}
	sort.Strings(names)
	type method struct {
		name  string
		pairs [][2]string
	}
	var methods []method
	for _, n := range names {
		if !want(n) {
			continue
		}
		descs := map[string]string{}
		collect(structs, n, n, descs, res, map[string]bool{})
		if len(descs) == 0 {
			if slices.Contains(opt.Types, n) {
				res.Notes = append(res.Notes, n+": no field has a comment")
			}
			continue
		}
		switch {
		case generic[n]:
			res.Notes = append(res.Notes, n+": a generic type gets no method; document its fields in a named, non-generic type")
			continue
		case hand[n]:
			res.Notes = append(res.Notes, n+": has a Descriptions method written by hand, which is left as it is")
			continue
		}
		m := method{name: n}
		for _, k := range sortedKeys(descs) {
			m.pairs = append(m.pairs, [2]string{k, descs[k]})
		}
		methods = append(methods, m)
		res.Types = append(res.Types, n)
	}
	if len(methods) == 0 {
		return res, nil
	}
	var b bytes.Buffer
	b.WriteString(header)
	fmt.Fprintf(&b, "\npackage %s\n", pkg)
	for _, m := range methods {
		fmt.Fprintf(&b, "\n// Descriptions returns the field descriptions of %s, taken from its doc comments (ADR 0020).\n", m.name)
		fmt.Fprintf(&b, "func (%s) Descriptions() map[string]string {\n\treturn map[string]string{\n", m.name)
		for _, p := range m.pairs {
			fmt.Fprintf(&b, "\t\t%s: %s,\n", strconv.Quote(p[0]), strconv.Quote(p[1]))
		}
		b.WriteString("\t}\n}\n")
	}
	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("docgen: formatting the output: %w\n%s", err, b.Bytes())
	}
	res.Source = src
	return res, nil
}

func recvName(e ast.Expr) string {
	switch e := e.(type) {
	case *ast.StarExpr:
		return recvName(e.X)
	case *ast.IndexExpr:
		return recvName(e.X)
	case *ast.Ident:
		return e.Name
	}
	return ""
}

// collect gathers the descriptions of the fields of structs[name], those of the structs it embeds
// by value from this package included (the codec reads them as the outer type's own fields, and
// a promoted method would be shadowed by the one written for the outer type).
func collect(structs map[string]*ast.StructType, root, name string, out map[string]string, res *Result, seen map[string]bool) {
	if seen[name] {
		return
	}
	seen[name] = true
	for _, f := range structs[name].Fields.List {
		text := commentText(f)
		if len(f.Names) == 0 { // embedded
			if id, ok := f.Type.(*ast.Ident); ok && structs[id.Name] != nil {
				collect(structs, root, id.Name, out, res, seen)
			}
			continue
		}
		if skipTag(f) {
			if text != "" {
				res.Notes = append(res.Notes, fmt.Sprintf("%s.%s: has a comment but is not on the wire (json:\"-\"), so it gets no description", root, f.Names[0].Name))
			}
			continue
		}
		for _, id := range f.Names {
			if !id.IsExported() {
				continue
			}
			if st, ok := f.Type.(*ast.StructType); ok && hasComments(st) {
				res.Notes = append(res.Notes, fmt.Sprintf("%s.%s: is an anonymous struct whose fields have comments; a method needs a named type, so name it and the generator will describe it", root, id.Name))
			}
			if text != "" {
				out[id.Name] = text
			}
		}
	}
}

func hasComments(st *ast.StructType) bool {
	for _, f := range st.Fields.List {
		if commentText(f) != "" {
			return true
		}
	}
	return false
}

func skipTag(f *ast.Field) bool {
	if f.Tag == nil {
		return false
	}
	s, err := strconv.Unquote(f.Tag.Value)
	if err != nil {
		return false
	}
	return reflect.StructTag(s).Get("json") == "-"
}

// commentText is the doc comment above a field, or the comment after it, as prose: the lines of
// a paragraph joined with one space and the paragraphs with a blank line.
func commentText(f *ast.Field) string {
	cg := f.Doc
	if cg == nil {
		cg = f.Comment
	}
	if cg == nil {
		return ""
	}
	var paras []string
	for _, p := range strings.Split(strings.TrimSpace(cg.Text()), "\n\n") {
		if p = strings.Join(strings.Fields(p), " "); p != "" {
			paras = append(paras, p)
		}
	}
	return strings.Join(paras, "\n\n")
}

func sortedKeys(m map[string]string) []string {
	ks := make([]string, 0, len(m))
	for k := range m {
		ks = append(ks, k)
	}
	sort.Strings(ks)
	return ks
}

// Write generates dir's file. It removes a stale one when nothing is left to describe, and
// returns whether the file changed.
func Write(dir string, opt Options) (*Result, bool, error) {
	res, err := Generate(dir, opt)
	if err != nil {
		return nil, false, err
	}
	path := filepath.Join(dir, FileName)
	old, rerr := os.ReadFile(path)
	if res.Source == nil {
		if rerr == nil {
			return res, true, os.Remove(path)
		}
		return res, false, nil
	}
	if rerr == nil && bytes.Equal(old, res.Source) {
		return res, false, nil
	}
	return res, true, os.WriteFile(path, res.Source, 0o644)
}
