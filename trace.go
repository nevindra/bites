// TraceID is the 16-byte id of a W3C trace (ADR 0059). The zero value is not a valid id.
type TraceID [16]byte

// String is the id as 32 lower-case hex digits, as traceparent and log lines write it. It
// allocates the string.
func (id TraceID) String() string { return hex.EncodeToString(id[:]) }

// SpanID is the 8-byte id of one span of a W3C trace (ADR 0059). The zero value is not a valid id.
type SpanID [8]byte

// String is the id as 16 lower-case hex digits. It allocates the string.
func (id SpanID) String() string { return hex.EncodeToString(id[:]) }

// Trace is a request's W3C trace context (ADR 0059): the trace it belongs to, the span this
// request is, the caller's span, the flags and the vendors' tracestate. With WithTraceContext the
// app reads it from the request's traceparent and tracestate headers, and gives the request a
// span id of its own; TraceFrom returns it to Providers, middleware, handlers and Observers.
type Trace struct {
	// ID is the trace, as the caller sent it, or new when the trace began here.
	ID TraceID
	// Span is this request's span, generated by the app for each request.
	Span SpanID
	// Parent is the caller's span, the parent-id of the traceparent it sent; zero when the trace
	// began here.
	Parent SpanID
	// Flags are the trace-flags as received; bit 0 (0x01) is sampled. A trace begun here has 0:
	// the core records no span, so it does not claim to have sampled one.
	Flags byte
	// State is the tracestate the caller sent, carried unchanged (several header lines joined with
	// a comma); "" when there was none, or when the traceparent was not valid.
	State string
}

// Sampled reports whether the sampled flag is set: the caller may have recorded the trace, and
// asks the services after it to record too.
func (t Trace) Sampled() bool { return t.Flags&0x01 != 0 }

// Child returns the trace context of an outgoing call made from this request: the same trace,
// flags and state, a new span id, and this request's span as its parent. Its Traceparent is the
// header to send with the call.
func (t Trace) Child() Trace {
	return Trace{ID: t.ID, Span: newSpanID(), Parent: t.Span, Flags: t.Flags, State: t.State}
}

// Traceparent is the traceparent header that names this span as the parent of the next one:
// "00-<ID>-<Span>-<Flags>", version 00 of W3C Trace Context, 55 bytes. It allocates the string;
// AppendTraceparent does not.
func (t Trace) Traceparent() string { return string(t.AppendTraceparent(make([]byte, 0, 55))) }

// AppendTraceparent appends what Traceparent returns to dst and returns the result.
func (t Trace) AppendTraceparent(dst []byte) []byte {
	dst = append(dst, "00-"...)
	dst = hex.AppendEncode(dst, t.ID[:])
	dst = append(dst, '-')
	dst = hex.AppendEncode(dst, t.Span[:])
	dst = append(dst, '-')
	return hex.AppendEncode(dst, []byte{t.Flags})
}

// ParseTraceparent reads a traceparent header value (W3C Trace Context): it returns the trace id,
// the caller's span as Parent and the flags, with Span zero and State empty, and false when the
// value is not valid. Valid is: two lower-case hex digits of version other than "ff", a 32-digit
// trace id and a 16-digit parent id that are not all zeros, two digits of flags, joined by '-';
// version 00 is exactly 55 bytes, and a later version may carry more after a further '-', which is
// ignored, as are its flags beyond sampled and random (0x03).
func ParseTraceparent(value string) (Trace, bool) { return parseTraceparent(value) }

func parseTraceparent[S string | []byte](s S) (Trace, bool) {
	var t Trace
	if len(s) < 55 || s[2] != '-' || s[35] != '-' || s[52] != '-' {
		return t, false
	}
	var v [1]byte
	if !unhexInto(v[:], s[0:2]) || v[0] == 0xff {
		return t, false
	}
	switch {
	case v[0] == 0 && len(s) != 55:
		return t, false
	case len(s) > 55 && s[55] != '-':
		return t, false
	}
	var f [1]byte
	if !unhexInto(t.ID[:], s[3:35]) || !unhexInto(t.Parent[:], s[36:52]) || !unhexInto(f[:], s[53:55]) {
		return t, false
	}
	if t.ID == (TraceID{}) || t.Parent == (SpanID{}) {
		return t, false
	}
	t.Flags = f[0]
	if v[0] != 0 {
		t.Flags &= 0x03
	}
	return t, true
}

// unhexInto decodes lower-case hex digits into dst, which is half as long as s.
func unhexInto[S string | []byte](dst []byte, s S) bool {
	for i := range dst {
		hi, lo := lowerHex(s[2*i]), lowerHex(s[2*i+1])
		if hi < 0 || lo < 0 {
			return false
		}
		dst[i] = byte(hi<<4 | lo)
	}
	return true
}

func lowerHex(c byte) int {
	switch {
	case '0' <= c && c <= '9':
		return int(c - '0')
	case 'a' <= c && c <= 'f':
		return int(c-'a') + 10
	}
	return -1
}

// newSpanID returns a random span id that is not zero, from math/rand/v2's per-thread ChaCha8
// generator: unique enough to tell spans apart, and not a secret.
func newSpanID() SpanID {
	for {
		if v := rand.Uint64(); v != 0 {
			var id SpanID
			for i := range id {
				id[i] = byte(v >> (56 - 8*i))
			}
			return id
		}
	}
}

func newTraceID() TraceID {
	var id TraceID
	for id == (TraceID{}) {
		a, b := rand.Uint64(), rand.Uint64()
		for i := range 8 {
			id[i], id[8+i] = byte(a>>(56-8*i)), byte(b>>(56-8*i))
		}
	}
	return id
}

// TraceContext configures WithTraceContext.
type TraceContext struct {
	// Begin makes a request that arrives with no valid traceparent begin a trace here: a new trace
	// id, a span id, no parent, and the flags 0 (not sampled), so every request has a trace id for
	// its log lines and its outgoing calls. Without it such a request has no Trace and an
	// outgoing call carries none, which leaves beginning a trace to the next service, as it was
	// without the option.
	Begin bool
}

// WithTraceContext makes the app take part in W3C Trace Context (ADR 0059). Every request's
// traceparent and tracestate headers are read before any Observer's Start and any middleware,
// and a request with a valid traceparent gets a Trace with a new span id of its own, which
// TraceFrom returns; with TraceContext.Begin a request without one begins a trace. Nothing is
// added to the answer. AccessLog writes trace_id and span_id when the request has a Trace.
//
// It costs a scan of the header lines for the two names and, when a trace is found or begun,
// its encoding in the request's slab (66 bytes and the tracestate), which allocates nothing.
// Giving it twice makes New panic.
func WithTraceContext(tc TraceContext) Option {
	return func(a *App) {
		where := callerWhere()
		if a.traceOn {
			panic(&RegistrationError{msg: "WithTraceContext: given twice (first at " + a.traceWhere + ", again at " + where + "): give one TraceContext"})
		}
		a.traceOn, a.traceBegin, a.traceWhere = true, tc.Begin, where
		a.custom["trace context"] = true
	}
}

// The encoding of a Trace in the request's context: the hex digits of ID (32), Span (16), Parent
// (16) and Flags (2), then State. Hex rather than bytes so that a log line slices the ids out of
// it without allocating.
const traceEncLen = 66

// beginTrace reads the request's trace context into its context (ADR 0059). The slab is made
// here when it is not yet, so callers size it first with AddSlab.
func (a *App) beginTrace(ex *engine.Exchange) {
	h := ex.Head()
	var tp []byte
	parents, stateLen, states := 0, 0, 0
	for i := range h.Headers {
		hd := &h.Headers[i]
		switch {
		case len(hd.Name) == 11 && foldBytes(hd.Name, "traceparent"):
			tp = hd.Value
			parents++
		case len(hd.Name) == 10 && foldBytes(hd.Name, "tracestate"):
			if len(hd.Value) > 0 {
				stateLen += len(hd.Value)
				states++
			}
		}
	}
	t, ok := Trace{}, false
	if parents == 1 {
		t, ok = parseTraceparent(tp)
	}
	if !ok {
		if !a.traceBegin {
			return
		}
		t = Trace{ID: newTraceID()}
		stateLen, states = 0, 0 // a tracestate without a valid traceparent is not carried
	}
	t.Span = newSpanID()
	n := traceEncLen + stateLen
	if states > 1 {
		n += states - 1
	}
	ex.AddSlab(n)
	b := ex.Slab().Reserve(n)
	encodeTrace(b, &t)
	if states > 0 {
		w := traceEncLen
		for i := range h.Headers {
			hd := &h.Headers[i]
			if len(hd.Name) == 10 && len(hd.Value) > 0 && foldBytes(hd.Name, "tracestate") {
				if w > traceEncLen {
					b[w] = ','
					w++
				}
				w += copy(b[w:], hd.Value)
			}
		}
	}
	ex.Context().SetTrace(unsafe.String(&b[0], len(b)))
}

// encodeTrace writes the hex of t's ids and flags into b[:traceEncLen].
func encodeTrace(b []byte, t *Trace) {
	hex.Encode(b[0:32], t.ID[:])
	hex.Encode(b[32:48], t.Span[:])
	hex.Encode(b[48:64], t.Parent[:])
	hex.Encode(b[64:66], []byte{t.Flags})
}

func foldBytes(b []byte, lower string) bool {
	for i := range len(lower) {
		c := b[i]
		if 'A' <= c && c <= 'Z' {
			c += 'a' - 'A'
		}
		if c != lower[i] {
			return false
		}
	}
	return true
}

// decodeTrace is the inverse of the encoding above.
func decodeTrace(s string) Trace {
	var t Trace
	var f [1]byte
	unhexInto(t.ID[:], s[0:32])
	unhexInto(t.Span[:], s[32:48])
	unhexInto(t.Parent[:], s[48:64])
	unhexInto(f[:], s[64:66])
	t.Flags, t.State = f[0], s[traceEncLen:]
	return t
}

type traceKey struct{}

// TraceFrom returns the trace context of ctx (ADR 0059): the one ContextWithTrace put in ctx or a
// context it derives from, or else that of the request ctx belongs to, which WithTraceContext or
// an Observer's Request.SetTrace gave it. It reports false when there is none. It works on a
// request's context after the request has ended too, since the trace is the request's own memory.
func TraceFrom(ctx context.Context) (Trace, bool) {
	if ctx == nil {
		return Trace{}, false
	}
	if t, ok := ctx.Value(traceKey{}).(Trace); ok {
		return t, true
	}
	if c := reqctx.Of(ctx); c != nil {
		if s := c.Trace(); s != "" {
			return decodeTrace(s), true
		}
	}
	return Trace{}, false
}

// ContextWithTrace returns a copy of ctx that TraceFrom answers with t: for work that is not a
// request (a job taken from a queue with a traceparent beside it) or a span of the application's
// own inside one. It allocates; a request's own trace costs nothing.
func ContextWithTrace(ctx context.Context, t Trace) context.Context {
	return context.WithValue(ctx, traceKey{}, t)
}

// SetTrace replaces the request's trace context, for an Observer's Start or a middleware before
// it calls next: a tracer that keeps its own span ids (the OpenTelemetry module) sets the span it
// began, so log lines and TraceFrom name the same span it records. A Trace whose ID or Span is
// zero removes the request's trace. It allocates the encoding (one string), and does nothing once
// the handler has returned.
func (r Request) SetTrace(t Trace) {
	if !r.live() {
		return
	}
	c := r.run.ex.Context()
	if c == nil {
		return
	}
	if t.ID == (TraceID{}) || t.Span == (SpanID{}) {
		c.SetTrace("")
		return
	}
	b := make([]byte, traceEncLen+len(t.State))
	encodeTrace(b, &t)
	copy(b[traceEncLen:], t.State)
	c.SetTrace(unsafe.String(&b[0], len(b)))
}

// traceHex returns the hex trace id and span id of the request ctx belongs to, as views of its
// encoded trace, so a log line costs no allocation for them; "" when it has none.
func traceHex(ctx context.Context) (id, span string) {
	if c := reqctx.Of(ctx); c != nil {
		if s := c.Trace(); s != "" {
			return s[0:32], s[32:48]
		}
	}
	return "", ""
}
